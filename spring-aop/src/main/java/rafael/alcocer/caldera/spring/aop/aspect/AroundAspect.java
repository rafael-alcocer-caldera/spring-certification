package rafael.alcocer.caldera.spring.aop.aspect;

import org.aspectj.lang.ProceedingJoinPoint;
import org.aspectj.lang.annotation.Around;
import org.aspectj.lang.annotation.Aspect;
import org.springframework.stereotype.Component;

@Aspect
@Component
public class AroundAspect {

    @Around("execution(void set*(*))")
    public Object aroundAspect(ProceedingJoinPoint joinPoint) throws Throwable {
        System.out.println("aroundAspect()... BEFORE");
        Object value = joinPoint.proceed();
        System.out.println("aroundAspect()... AFTER");
        return value;
    }
}
